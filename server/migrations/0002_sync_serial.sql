-- Очередь записи изменений и эпоха синхронизации.
--
-- Каждая транзакция, которая пишет в change_log, сначала блокирует
-- единственную строку этой таблицы (SELECT … FOR UPDATE) и держит её до
-- COMMIT. Записи идут строго по очереди, поэтому порядок seq совпадает с
-- порядком фиксации: клиент, прочитавший изменения до seq = N, не пропустит
-- изменение с меньшим номером, зафиксированное позже.
--
-- epoch — метка «поколения» журнала изменений. Клиент хранит её вместе с
-- курсором; если она сменилась (база восстановлена из копии и seq пошли
-- заново), клиент обязан синхронизироваться с нуля. После восстановления
-- из копии эпоху меняют: UPDATE sync_serial SET epoch = UUID();
CREATE TABLE sync_serial (
  id TINYINT NOT NULL,
  epoch CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  PRIMARY KEY (id),
  CHECK (id = 1)
);

INSERT INTO sync_serial (id, epoch) VALUES (1, UUID());
