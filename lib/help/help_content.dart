/// Для кого инструкция.
enum HelpRole {
  operator('Оператор', 'оператора'),
  accountant('Бухгалтер', 'бухгалтера'),
  admin('Администратор', 'администратора');

  final String title;

  /// «Инструкция для …».
  final String genitive;

  const HelpRole(this.title, this.genitive);
}

const _all = {HelpRole.operator, HelpRole.accountant, HelpRole.admin};
const _office = {HelpRole.accountant, HelpRole.admin};
const _admin = {HelpRole.admin};
const _operator = {HelpRole.operator};

/// Кусок раздела. [roles] — кому он нужен (по умолчанию — всем, кому нужен
/// раздел).
sealed class HelpBlock {
  final Set<HelpRole>? roles;
  const HelpBlock({this.roles});

  bool isFor(HelpRole role) => roles?.contains(role) ?? true;
}

/// Абзац.
class HelpText extends HelpBlock {
  final String text;
  const HelpText(this.text, {super.roles});
}

/// Подзаголовок.
class HelpHeading extends HelpBlock {
  final String text;
  const HelpHeading(this.text, {super.roles});
}

/// Список.
class HelpList extends HelpBlock {
  final List<String> items;

  /// Нумерованный (шаги).
  final bool numbered;

  const HelpList(this.items, {this.numbered = false, super.roles});
}

/// Важное замечание.
class HelpNote extends HelpBlock {
  final String text;
  const HelpNote(this.text, {super.roles});
}

/// Снимок экрана `assets/help/[name].png` с подписью.
class HelpImage extends HelpBlock {
  final String name;
  final String caption;

  /// Снимок телефона (узкий) — показывается уже.
  final bool phone;

  const HelpImage(this.name, this.caption, {this.phone = false, super.roles});

  String get asset => 'assets/help/$name.png';
}

class HelpChapter {
  final String id;
  final String title;
  final Set<HelpRole> roles;
  final List<HelpBlock> blocks;

  const HelpChapter({
    required this.id,
    required this.title,
    required this.roles,
    required this.blocks,
  });

  /// Куски раздела для роли.
  List<HelpBlock> blocksFor(HelpRole role) => [
    for (final b in blocks)
      if (b.isFor(role)) b,
  ];
}

/// Разделы инструкции для роли — по порядку.
List<HelpChapter> helpFor(HelpRole role) => [
  for (final c in helpChapters)
    if (c.roles.contains(role)) c,
];

/// Все снимки экранов, на которые ссылается инструкция.
Set<String> get helpImageNames => {
  for (final c in helpChapters)
    for (final b in c.blocks)
      if (b is HelpImage) b.name,
};

